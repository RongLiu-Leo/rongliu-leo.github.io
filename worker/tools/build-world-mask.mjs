// Rasterizes Natural Earth 110m country outlines into a packed bitmask so the
// visitor map can draw a dotted world without shipping any geometry library.
//
//   node worker/tools/build-world-mask.mjs <path-to-ne_110m_admin_0_countries.geojson>
//
// Source: https://github.com/nvkelso/natural-earth-vector (public domain)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const W = 240;
const H = 95;
const LAT_MAX = 84;
const LAT_MIN = -58; // Antarctica omitted; it only adds a blank band.

const source = process.argv[2];
if (!source) {
  console.error("usage: build-world-mask.mjs <countries.geojson>");
  process.exit(1);
}

const geo = JSON.parse(readFileSync(source, "utf8"));

const rings = [];
for (const feature of geo.features) {
  const g = feature.geometry;
  if (!g) continue;
  const polygons = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
      for (const [x, y] of ring) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
      rings.push({ ring, minX, maxX, minY, maxY });
    }
  }
}

// Even-odd fill: holes fall out of the parity count without special handling.
function isLand(lon, lat) {
  let inside = false;
  for (const { ring, minX, maxX, minY, maxY } of rings) {
    if (lon < minX || lon > maxX || lat < minY || lat > maxY) continue;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
  }
  return inside;
}

const bytes = new Uint8Array(Math.ceil((W * H) / 8));
let landCells = 0;

for (let row = 0; row < H; row++) {
  const lat = LAT_MAX - ((row + 0.5) * (LAT_MAX - LAT_MIN)) / H;
  for (let col = 0; col < W; col++) {
    const lon = -180 + ((col + 0.5) * 360) / W;
    if (!isLand(lon, lat)) continue;
    const bit = row * W + col;
    bytes[bit >> 3] |= 128 >> (bit & 7);
    landCells++;
  }
}

const outPath = resolve(dirname(fileURLToPath(import.meta.url)), "../../assets/js/world-mask.js");
writeFileSync(
  outPath,
  `// Generated by worker/tools/build-world-mask.mjs from Natural Earth 110m data.
// ${W}x${H} equirectangular land bitmask, latitudes ${LAT_MAX} to ${LAT_MIN}.
window.WORLD_LAND_MASK = {
  w: ${W},
  h: ${H},
  latMax: ${LAT_MAX},
  latMin: ${LAT_MIN},
  bits: "${Buffer.from(bytes).toString("base64")}"
};
`,
  "utf8"
);

console.log(`${landCells} land cells of ${W * H}; wrote ${outPath}`);
